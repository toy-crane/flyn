/**
 * 한 화의 무대. 사람이 미리 써 두는 부분이 전부 여기에 모인다.
 *
 * 사건, 인물, 첫 장면, 진행 규칙이 각본이고 그 뒤의 대사와 전개는 모델이
 * 쓴다. 예고도 사람이 쓴다. 다음 화의 사건이 정해져 있어야 예고가 어긋나지
 * 않기 때문이다.
 */
export interface EpisodeScript {
  /** 말풍선이 될 수 있는 이름. 목록에 없는 줄 머리는 전부 지문으로 흐른다. */
  cast: readonly string[];
  /** 사건이 어떻게 끝났다고 볼지. 종류마다 한 줄씩 프롬프트에 들어간다. */
  endings: {
    compromise: string;
    failure: string;
    success: string;
  };
  /** 화 번호. 1부터 시작하고 배열의 자리와 같다. */
  number: number;
  /** 사용자가 입력하기 전에 열리는 첫 장면. */
  opening: string;
  /**
   * 이 화를 예고하는 한두 줄.
   *
   * 앞 화의 마무리와 홈의 다음 이야기 카드가 같은 문장을 쓴다. 1화의 예고는
   * 아직 아무 화도 끝나지 않은 사람이 홈에서 처음 읽는 문장이다.
   */
  preview: string;
  /** 상황 줄. 무슨 일이 벌어졌고 무엇을 하면 되는지 한 줄로 남긴다. */
  situation: string;
  /** 상황 줄 앞에 붙는 그림 하나. 낭독에는 들어가지 않는다. */
  situationEmoji: string;
  /** 이 화만의 무대. 공통 규칙과 합쳐져 하나의 프롬프트가 된다. */
  stage: string;
  /** 화의 이름. 홈 카드와 에피소드 헤더에 그대로 보인다. */
  title: string;
}

